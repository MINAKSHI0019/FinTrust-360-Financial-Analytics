
-- 1. Total Complaints
SELECT COUNT(*) AS TOTAL_COMPLAINTS
FROM FINTRUST_COMPLAINTS;

-- 2. Monthly Complaints
SELECT TO_CHAR(DATE_RECEIVED, 'MM-YYYY') AS MONTH,
       COUNT(*) AS TOTAL
FROM FINTRUST_COMPLAINTS
GROUP BY TO_CHAR(DATE_RECEIVED, 'MM-YYYY')
ORDER BY MIN(DATE_RECEIVED);

-- 3. Complaints by Financial Product
SELECT FINANCIAL_PRODUCT, COUNT(*) AS TOTAL
FROM FINTRUST_COMPLAINTS
GROUP BY FINANCIAL_PRODUCT
ORDER BY TOTAL DESC;

-- 4. Most Reported Issues
SELECT ISSUE_CATEGORY, COUNT(*) AS TOTAL
FROM FINTRUST_COMPLAINTS
GROUP BY ISSUE_CATEGORY
ORDER BY TOTAL DESC;

-- 5. Complaints by Company
SELECT COMPANY_NAME, COUNT(*) AS TOTAL
FROM FINTRUST_COMPLAINTS
GROUP BY COMPANY_NAME
ORDER BY TOTAL DESC;

-- 6. Complaints by State
SELECT STATE, COUNT(*) AS TOTAL
FROM FINTRUST_COMPLAINTS
GROUP BY STATE
ORDER BY TOTAL DESC;

-- 7. Timely Response Percentage (Open complaints are excluded.)
SELECT COMPANY_NAME,
       ROUND(SUM(CASE WHEN TIMELY_RESPONSE_CLEAN = 'Yes'
                      THEN 1 ELSE 0 END) * 100 / COUNT(*), 2)
           AS TIMELY_PERCENTAGE
FROM FINTRUST_COMPLAINTS
WHERE RESPONSE_STATUS = 'Closed'
  AND DATE_COMPANY_RESPONDED IS NOT NULL
GROUP BY COMPANY_NAME
ORDER BY TIMELY_PERCENTAGE DESC;

-- 8. Average Response Time (Open complaints are excluded.)
SELECT ROUND(AVG(RESPONSE_TIME_DAYS), 2) AS AVERAGE_DAYS
FROM FINTRUST_COMPLAINTS
WHERE RESPONSE_STATUS = 'Closed'
  AND DATE_COMPANY_RESPONDED IS NOT NULL;

-- 9. Open and Closed Complaints
SELECT RESPONSE_STATUS, COUNT(*) AS TOTAL
FROM FINTRUST_COMPLAINTS
GROUP BY RESPONSE_STATUS;

-- 10. Complaints by Submission Channel
SELECT SUBMISSION_CHANNEL, COUNT(*) AS TOTAL
FROM FINTRUST_COMPLAINTS
GROUP BY SUBMISSION_CHANNEL
ORDER BY TOTAL DESC;
